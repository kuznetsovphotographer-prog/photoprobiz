async (page) => {
  const checks = [];
  const check = (name, valid, detail) => {
    checks.push({ name, pass: Boolean(valid), detail });
    if (!valid) throw new Error(`${name}: ${JSON.stringify(detail)}`);
  };
  const activeDot = () => page.locator('.pp-gallery__dot[aria-current="true"]').getAttribute('aria-label');
  await page.getByRole('button', { name: 'Открыть серию', exact: true }).click();
  await page.locator('.pp-gallery__image').evaluate(img => img.decode());
  check('Dialog opens and isolates main', await page.locator('#fixture-main').evaluate(el => el.inert), await page.locator('[role="dialog"]').count());
  const desktop = await page.locator('.pp-gallery__image').boundingBox();
  check('Desktop natural photo width 860', desktop.width === 860, desktop);
  await page.screenshot({path:'output/playwright/local-gallery-desktop.png'});
  await page.getByRole('button', { name: 'Предыдущая фотография' }).click();
  check('Previous wraps to last', (await activeDot()) === 'Фотография 19 из 19', await activeDot());
  await page.getByRole('button', { name: 'Следующая фотография' }).click();
  check('Next wraps to first', (await activeDot()) === 'Фотография 1 из 19', await activeDot());
  await page.keyboard.press('ArrowRight');
  check('Keyboard ArrowRight', (await activeDot()) === 'Фотография 2 из 19', await activeDot());
  await page.keyboard.press('ArrowLeft');
  check('Keyboard ArrowLeft', (await activeDot()) === 'Фотография 1 из 19', await activeDot());
  await page.getByRole('button', { name: 'Фотография 7 из 19', exact: true }).click();
  check('Direct dot selection', (await activeDot()) === 'Фотография 7 из 19', await activeDot());
  await page.getByRole('button', { name: 'Закрыть окно' }).focus();
  await page.keyboard.press('Shift+Tab');
  check('Focus traps backwards', await page.locator('.pp-gallery__dot').last().evaluate(el => el === document.activeElement), null);
  await page.keyboard.press('Tab');
  check('Focus traps forwards', await page.getByRole('button', { name: 'Закрыть окно' }).evaluate(el => el === document.activeElement), null);
  await page.keyboard.press('Escape');
  check('Escape restores trigger and main', await page.locator('#open-gallery').evaluate(el => el === document.activeElement && !document.querySelector('main').inert), await page.locator('[role="dialog"]').count());
  await page.evaluate(() => { scrollTo(0, 600); document.querySelector('#open-gallery').click(); });
  await page.locator('[role="dialog"]').waitFor();
  check('Opening preserves original scroll in lock', await page.evaluate(() => document.body.style.top === '-600px' && document.body.style.position === 'fixed'), await page.evaluate(() => document.body.style.cssText));
  await page.keyboard.press('Escape');
  check('Closing restores page scroll', await page.evaluate(() => scrollY === 600 && !document.body.style.position), await page.evaluate(() => scrollY));
  await page.getByRole('button', { name: 'Открыть форму', exact: true }).click();
  await page.getByRole('textbox', { name: 'Имя' }).fill('Иван');
  await page.getByRole('button', { name: 'Политика', exact: true }).click();
  check('Nested dialog isolates previous dialog', await page.getByRole('dialog', { name: 'Контрольная форма', includeHidden: true }).evaluate(el => el.inert), await page.locator('[role="dialog"]').count());
  await page.keyboard.press('Escape');
  check('Nested Escape restores form and focus', await page.getByRole('button', { name: 'Политика', exact: true }).evaluate(el => el === document.activeElement && document.querySelector('main').inert), await page.getByRole('textbox', { name: 'Имя' }).inputValue());
  check('Nested form values retained', (await page.getByRole('textbox', { name: 'Имя' }).inputValue()) === 'Иван', null);
  await page.keyboard.press('Escape');
  check('Last dialog releases main and scroll lock', await page.locator('#fixture-main').evaluate(el => !el.inert && !document.body.style.position), await page.locator('[role="dialog"]').count());
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', { name: 'Открыть серию', exact: true }).click();
  await page.locator('.pp-gallery__image').evaluate(img => img.decode());
  const mobile = await page.locator('.pp-gallery__image').boundingBox();
  check('Mobile natural photo fills width', mobile.width === 390 && mobile.x === 0, mobile);
  check('Mobile no horizontal overflow', await page.locator('[role="dialog"]').evaluate(el => el.scrollWidth === el.clientWidth), null);
  await page.screenshot({path:'output/playwright/local-gallery-mobile.png'});
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:280,y:400}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:160,y:402}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:80,y:404}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await cdp.detach();
  check('Real touch swipe advances photo', (await activeDot()) === 'Фотография 2 из 19', await activeDot());
  await page.mouse.click(2, 80);
  check('Backdrop closes', (await page.locator('[role="dialog"]').count()) === 0, await page.locator('[role="dialog"]').count());
  return { checks, desktop, mobile };
}
